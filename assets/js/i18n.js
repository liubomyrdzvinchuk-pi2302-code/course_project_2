function getLang() {
  try {
    return localStorage.getItem('lang') === 'en' ? 'en' : 'uk';
  } catch (error) {
    return 'uk';
  }
}

// Returns a text for scripts, for example t('error').
function t(key) {
  var lang = getLang();
  return (TEXTS[lang] && TEXTS[lang][key]) || TEXTS.uk[key] || key;
}

var TRANSLATED_ATTRIBUTES = ['placeholder', 'aria-label', 'alt', 'content'];

// Replaces the texts of the page. The original Ukrainian text is remembered in data-uk.
function applyLanguage(lang) {
  document.documentElement.lang = lang;

  var nodes = document.querySelectorAll('[data-i18n]');
  for (var i = 0; i < nodes.length; i++) {
    var node = nodes[i];
    if (node.dataset.uk === undefined) node.dataset.uk = node.textContent;
    var translated = TEXTS.en[node.dataset.i18n];
    node.textContent = lang === 'en' && translated ? translated : node.dataset.uk;
  }

  TRANSLATED_ATTRIBUTES.forEach(function (name) {
    var datasetKey = 'i18n' + name.charAt(0).toUpperCase() + name.slice(1).replace(/-(\w)/g, function (m, c) { return c.toUpperCase(); });
    var originalKey = 'uk' + datasetKey.slice(4);
    var elements = document.querySelectorAll('[data-i18n-' + name + ']');
    for (var j = 0; j < elements.length; j++) {
      var element = elements[j];
      if (element.dataset[originalKey] === undefined) element.dataset[originalKey] = element.getAttribute(name);
      var text = TEXTS.en[element.dataset[datasetKey]];
      element.setAttribute(name, lang === 'en' && text ? text : element.dataset[originalKey]);
    }
  });

  var buttons = document.querySelectorAll('.lang-switch button');
  for (var k = 0; k < buttons.length; k++) {
    buttons[k].setAttribute('aria-pressed', String(buttons[k].dataset.lang === lang));
  }
}

function setLanguage(lang) {
  try {
    localStorage.setItem('lang', lang);
  } catch (error) {
    // the choice just will not be remembered
  }
  applyLanguage(lang);
  document.dispatchEvent(new CustomEvent('languagechange'));
}
